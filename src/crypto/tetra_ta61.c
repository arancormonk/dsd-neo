/* The rotation and constant of each round key (upstream HURDLE_set_key_fw()): round key i is round key i - 1 rotated
 * left by k_hurdle_rotation[i] bytes, XORed with k_hurdle_round_constant; round key 0 is the key. */
static const uint8_t k_hurdle_rotation[16] = {5, 5, 5, 5, 5, 3, 7, 5, 5, 5, 5, 7, 3, 5, 5, 5};
static const uint8_t k_hurdle_round_constant[16] = {0x3C, 0xA7, 0xEC, 0x25, 0x79, 0x57, 0xDF, 0xC0,
                                                    0x38, 0x0A, 0x33, 0x1E, 0xF3, 0x8C, 0xF4, 0xF7};

/* The bits a round function nibble spreads over the four output bytes: bit 0 of the nibble to bit 7 of byte 0, bit 1
 * to bit 7 of byte 1, and so on (upstream's little-endian g_adwReorder). */
static const uint32_t k_hurdle_reorder[16] = {
    0x00000000U, 0x80000000U, 0x00800000U, 0x80800000U, 0x00008000U, 0x80008000U, 0x00808000U, 0x80808000U,
    0x00000080U, 0x80000080U, 0x00800080U, 0x80800080U, 0x00008080U, 0x80008080U, 0x00808080U, 0x80808080U,
};

enum { HURDLE_ROUNDS = 16, HURDLE_KEY_BYTES = 16 };

/* The 16 round keys of 16 bytes from the 128-bit key @p key. */
static void
hurdle_set_key(const uint8_t key[HURDLE_KEY_BYTES], uint8_t round_keys[HURDLE_ROUNDS * HURDLE_KEY_BYTES]) {
    DSD_MEMCPY(round_keys, key, HURDLE_KEY_BYTES);
    for (int i = 1; i < HURDLE_ROUNDS; i++) {
        const uint8_t* const prev = round_keys + ((size_t)(i - 1) * HURDLE_KEY_BYTES);
        uint8_t* const rk = round_keys + ((size_t)i * HURDLE_KEY_BYTES);
        for (int j = 0; j < HURDLE_KEY_BYTES; j++) {
            rk[j] = (uint8_t)(prev[(j + k_hurdle_rotation[i]) & 0x0F] ^ k_hurdle_round_constant[j]);
        }
    }
}

/* The round function: four output bytes from the right half @p rhs and round key @p rk. */
static void
hurdle_f(uint8_t out[4], const uint8_t rhs[4], const uint8_t* rk) {
    /* Which input byte and round key byte each of the 12 S-box steps adds, in order. */
    static const uint8_t k_in[12] = {3, 2, 1, 0, 3, 1, 2, 0, 1, 3, 0, 2};
    static const uint8_t k_rk[12] = {15, 14, 13, 12, 11, 10, 9, 8, 7, 6, 5, 4};
    uint32_t bits = 0;
    uint8_t s = 0;
    for (int i = 0; i < 12; i++) {
        s = k_hurdle_sbox[(uint8_t)((uint8_t)(rhs[k_in[i]] + rk[k_rk[i]]) ^ s)];
        if (i >= 4) {
            bits = (bits >> 1) | k_hurdle_reorder[s & 0x0Fu];
        }
    }
    out[0] = (uint8_t)(bits & 0xFFu);
    out[1] = (uint8_t)((bits >> 8) & 0xFFu);
    out[2] = (uint8_t)((bits >> 16) & 0xFFu);
    out[3] = (uint8_t)((bits >> 24) & 0xFFu);
}

/* One 64-bit block encrypted under @p round_keys (16 Feistel rounds). */
static void
hurdle_encrypt(uint8_t out[8], const uint8_t in[8], const uint8_t* round_keys) {
    uint8_t lhs[4];
    uint8_t rhs[4];
    uint8_t tmp[4];
    DSD_MEMCPY(lhs, in, sizeof lhs);
    DSD_MEMCPY(rhs, in + 4, sizeof rhs);
    for (int i = 0; i < HURDLE_ROUNDS; i++) {
        hurdle_f(tmp, rhs, round_keys + ((size_t)i * HURDLE_KEY_BYTES));
        for (int j = 0; j < 4; j++) {
            tmp[j] = (uint8_t)(tmp[j] ^ lhs[j]);
        }
        DSD_MEMCPY(lhs, rhs, sizeof lhs);
        DSD_MEMCPY(rhs, tmp, sizeof rhs);
    }
    DSD_MEMCPY(out, rhs, 4);
    DSD_MEMCPY(out + 4, lhs, 4);
    DSD_SECURE_ZERO(lhs, sizeof lhs);
    DSD_SECURE_ZERO(rhs, sizeof rhs);
    DSD_SECURE_ZERO(tmp, sizeof tmp);
}

/* The 128-bit HURDLE key TA61 makes of an 80-bit cipher key (upstream transform_80_to_128()). */
static void
ta61_expand_key(const uint8_t key[10], uint8_t out[HURDLE_KEY_BYTES]) {
    for (int i = 0; i < 5; i++) {
        out[1 + (3 * i)] = (uint8_t)(key[i] + key[9 - i]);
        out[2 + (3 * i)] = key[i];
        out[3 + (3 * i)] = key[9 - i];
    }
    out[0] = (uint8_t)(out[1] ^ out[4] ^ out[7] ^ out[10] ^ out[13]);
}

/* TA61's intermediate key c: the HURDLE encryption under the expanded key of key[i] ^ key[i + 2]. */
static void
ta61_intermediate(const uint8_t key[10], uint8_t c[8]) {
    uint8_t expanded[HURDLE_KEY_BYTES];
    uint8_t round_keys[HURDLE_ROUNDS * HURDLE_KEY_BYTES];
    uint8_t block[8];
    ta61_expand_key(key, expanded);
    hurdle_set_key(expanded, round_keys);
    for (int i = 0; i < 8; i++) {
        block[i] = (uint8_t)(key[i] ^ key[i + 2]);
    }
    hurdle_encrypt(c, block, round_keys);
    DSD_SECURE_ZERO(expanded, sizeof expanded);
    DSD_SECURE_ZERO(round_keys, sizeof round_keys);
    DSD_SECURE_ZERO(block, sizeof block);
}

static void
ta61_transform(uint8_t id[3]) {
    const uint8_t a = (uint8_t)((uint8_t)((uint8_t)(id[1] + id[0]) << 1) - id[2]);
    const uint8_t b = (uint8_t)((uint8_t)((uint8_t)(id[2] + id[0]) << 1) - id[1]);
    const uint8_t d = (uint8_t)((uint8_t)((uint8_t)(id[2] + id[1]) << 1) - id[0]);
    id[0] = k_hurdle_sbox[a];
    id[1] = k_hurdle_sbox[b];
    id[2] = k_hurdle_sbox[d];
}

static void
ta61_transform_inverse(uint8_t id[3]) {
    const uint32_t x = k_hurdle_inv_sbox[id[0]];
    const uint32_t y = k_hurdle_inv_sbox[id[1]];
    const uint32_t z = k_hurdle_inv_sbox[id[2]];
    /* Modulo 256, 114 and -57 (199) invert the transform's mixing. */
    id[0] = (uint8_t)((114U * x + 114U * y + 199U * z) & 0xFFU);
    id[1] = (uint8_t)((114U * x + 199U * y + 114U * z) & 0xFFU);
    id[2] = (uint8_t)((199U * x + 114U * y + 114U * z) & 0xFFU);
}

static void
ta61_xor(uint8_t id[3], const uint8_t c[8], int i0, int i1, int i2) {
    id[0] = (uint8_t)(id[0] ^ c[i0]);
    id[1] = (uint8_t)(id[1] ^ c[i1]);
    id[2] = (uint8_t)(id[2] ^ c[i2]);
}

static void
ta61_run(const uint8_t key[10], uint32_t in, uint32_t* out, int decrypt) {
    uint8_t c[8];
    uint8_t id[3] = {(uint8_t)((in >> 16) & 0xFFU), (uint8_t)((in >> 8) & 0xFFU), (uint8_t)(in & 0xFFU)};
    ta61_intermediate(key, c);
    if (!decrypt) {
        ta61_xor(id, c, 0, 3, 6);
        ta61_transform(id);
        ta61_xor(id, c, 1, 4, 7);
        ta61_transform(id);
        ta61_xor(id, c, 2, 5, 0);
    } else {
        ta61_xor(id, c, 2, 5, 0);
        ta61_transform_inverse(id);
        ta61_xor(id, c, 1, 4, 7);
        ta61_transform_inverse(id);
        ta61_xor(id, c, 0, 3, 6);
    }
    *out = ((uint32_t)id[0] << 16) | ((uint32_t)id[1] << 8) | (uint32_t)id[2];
    DSD_SECURE_ZERO(c, sizeof c);
    DSD_SECURE_ZERO(id, sizeof id);
}

void
tetra_ta61_encrypt(const uint8_t key[10], uint32_t ssi, uint32_t* esi) {
    if (key && esi) {
        ta61_run(key, ssi & 0xFFFFFFU, esi, 0);
    }
}

void
tetra_ta61_decrypt(const uint8_t key[10], uint32_t esi, uint32_t* ssi) {
    if (key && ssi) {
        ta61_run(key, esi & 0xFFFFFFU, ssi, 1);
    }
}
