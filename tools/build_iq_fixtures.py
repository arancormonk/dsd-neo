"""Regenerate the full-chain I/Q decode fixtures in tests/fixtures/iq.

The fixtures are short cu8 baseband captures plus dsd-neo-iq metadata sidecars.
Replaying them with --iq-replay drives the complete chain (decimation, filtering,
discriminator/CQPSK timing, symbol slicer, frame sync, protocol layer), which is
what the DECODE_IQ_* CTest cases assert against.

Two source kinds feed the same output format:

  "iq"     the upstream recording already is complex baseband; it is resampled to
           48 kHz and requantized to cu8.
  "audio"  the upstream recording is FM discriminator audio with no I/Q. Because
           FM demodulation is invertible, the audio is treated as instantaneous
           frequency and integrated back into a complex baseband signal. The
           result exercises the same demodulation chain, but carries none of the
           original RF impairments (noise, fading, adjacent-channel energy).

Fixtures are committed, so this script is provenance and regeneration only -- it
is not run by CI and needs network access plus ffmpeg. Regenerated bytes are not
guaranteed bit-identical across ffmpeg versions; re-run the DECODE_IQ_* tests
after regenerating.

Usage:
    python3 tools/build_iq_fixtures.py [--out tests/fixtures/iq] [--cache .iq-cache]
"""

