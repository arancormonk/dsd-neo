def verify_sha256(key, path):
    """Check path against the pinned hash in SHA256SUMS (which must exist)."""
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    actual = digest.hexdigest()
    expected = SHA256SUMS[key]
    if actual != expected:
        raise ValueError(
            f"SHA-256 mismatch for {key} ({path}):\n"
            f"  expected {expected}\n"
            f"  actual   {actual}\n"
            "Upstream content changed (or the cache is corrupt). Delete the cached "
            "file to re-download; if the change is legitimate, update SHA256SUMS "
            "and re-run the DECODE_IQ_* tests."
        )


def fetch(cache_dir, key, url):
    """Download url into cache_dir, returning the local path.

    Only the hard-coded https URLs in SOURCES are ever fetched; the scheme guard
    below rejects anything else so a local file:// or ftp:// path cannot be
    substituted by editing a source list entry. Every download (cached or fresh)
    is verified against the pinned SHA-256 in SHA256SUMS.
    """
    if not url.startswith("https://"):
        raise ValueError(f"refusing non-https fixture source for {key}: {url}")
    path = os.path.join(cache_dir, key + os.path.splitext(url)[1])
    if os.path.exists(path) and os.path.getsize(path) > 0:
        verify_sha256(key, path)
        return path
    # URLs come only from the SOURCES constant above and are guarded to https.
    req = urllib.request.Request(url, headers={"User-Agent": "dsd-neo-fixture-builder"})  # nosemgrep: python.lang.security.audit.dynamic-urllib-use-detected.dynamic-urllib-use-detected
    with urllib.request.urlopen(req) as resp:  # nosemgrep: python.lang.security.audit.dynamic-urllib-use-detected.dynamic-urllib-use-detected
        data = resp.read()
    with open(path, "wb") as handle:
        handle.write(data)
    verify_sha256(key, path)
    return path


def resolve_local(cache_dir, key):
    """Locate a user-contributed source in cache_dir, or None if absent."""
    path = os.path.join(cache_dir, LOCAL_SOURCES[key])
    if not os.path.exists(path) or os.path.getsize(path) == 0:
        return None
    verify_sha256(key, path)
    return path


def extract_zip_members(cache_dir, key, archive_path):
    """Extract the members named in ZIP_MEMBERS[key], returning {name: path}."""
    out = {}
    with zipfile.ZipFile(archive_path) as zf:
        for name, member in ZIP_MEMBERS[key].items():
            dest = os.path.join(cache_dir, name + ".wav")
            if not os.path.exists(dest):
                with open(dest, "wb") as handle:
                    handle.write(zf.read(member))
            out[name] = dest
    return out


def ffmpeg_read(path, channels, start_s, duration_s):
    """Decode path to float32 PCM at SAMPLE_RATE_HZ with the requested channel count."""
    cmd = ["ffmpeg", "-v", "error"]
    if start_s:
        cmd += ["-ss", str(start_s)]
    cmd += ["-i", path]
    if duration_s:
        cmd += ["-t", str(duration_s)]
    cmd += ["-f", "f32le", "-ac", str(channels), "-ar", str(SAMPLE_RATE_HZ), "-"]
    proc = subprocess.run(cmd, capture_output=True, check=True)
    return np.frombuffer(proc.stdout, dtype=np.float32).astype(np.float64)


def load_iq(path, start_s, duration_s):
    raw = ffmpeg_read(path, 2, start_s, duration_s)
    return raw[0::2] + 1j * raw[1::2]


def remodulate(audio, deviation):
    """Integrate discriminator audio back into complex baseband (inverse FM demod)."""
    audio = audio - np.mean(audio)
    scale = np.percentile(np.abs(audio), 99.5)
    if scale <= 0.0:
        scale = 1.0
    freq = audio / scale * deviation
    phase = np.cumsum(freq) * math.pi
    return np.exp(1j * phase)


def to_cu8(samples, headroom=0.9, normalize=True):
    """Quantize complex baseband to interleaved unsigned 8-bit I/Q.

    normalize=False keeps the caller's amplitude, which matters for noise: scaling it to
    full scale would set the level from whichever sample happened to be the largest.
    """
    real = np.real(samples)
    imag = np.imag(samples)
    scale = headroom
    if normalize:
        peak = max(np.max(np.abs(real)), np.max(np.abs(imag)))
        if peak <= 0.0:
            peak = 1.0
        scale = headroom / peak
    interleaved = np.empty(len(samples) * 2)
    interleaved[0::2] = real * scale
    interleaved[1::2] = imag * scale
    return np.clip(np.round(interleaved * 127.5 + 127.5), 0, 255).astype(np.uint8)


def write_fixture(out_dir, name, samples, normalize=True):
    payload = to_cu8(samples, normalize=normalize)
    data_name = name + ".iq"
    data_path = os.path.join(out_dir, data_name)
    with open(data_path, "wb") as handle:
        handle.write(payload.tobytes())
    metadata = METADATA_TEMPLATE.format(
        sample_rate=SAMPLE_RATE_HZ,
        bw_khz=DSP_BW_KHZ,
        demod_rate=SAMPLE_RATE_HZ,
        data_file=data_name,
        data_bytes=len(payload),
    )
    with open(data_path + ".json", "w", encoding="utf-8") as handle:
        handle.write(metadata)
    return len(payload)


def load_cu8_fixture(path):
    """Read a committed cu8 fixture back into complex baseband."""
    raw = np.fromfile(path, dtype=np.uint8).astype(np.float64)
    centered = (raw - 127.5) / 127.5
    return centered[0::2] + 1j * centered[1::2]


def simulcast_two_ray(samples, delay_samples, amp2, cfo_hz, phase2):
    """Sum the signal with a delayed, attenuated, frequency-offset copy."""
    if delay_samples > 0:
        delayed = np.concatenate([np.zeros(delay_samples, dtype=samples.dtype), samples[:-delay_samples]])
    else:
        delayed = samples
    n = np.arange(len(samples))
    rotation = np.exp(1j * (2.0 * math.pi * cfo_hz * n / SAMPLE_RATE_HZ + phase2))
    return samples + amp2 * delayed * rotation


def build_noise(out_dir):
    """Write the open-squelch receiver-noise fixtures (issue #398)."""
    total = 0
    for name, seed, duration_s, sigma_lsb in DERIVED_NOISE:
        rng = np.random.default_rng(seed)
        count = int(round(duration_s * SAMPLE_RATE_HZ))
        sigma = sigma_lsb / 127.5
        samples = rng.normal(0.0, sigma, count) + 1j * rng.normal(0.0, sigma, count)
        written = write_fixture(out_dir, name, samples, normalize=False)
        total += written
        print(f"{name:28s} noise   {written // 1024:6d} KiB")
    return total


def load_dpmr_reference_vectors():
    """Import the dPMR CCH vector generator so fixture and unit test share one source."""
    import importlib.util

    path = os.path.join(
        os.path.dirname(os.path.abspath(__file__)),
        "..",
        "tests",
        "protocol",
        "dpmr",
        "fixtures",
        "generate_dpmr_reference_vectors.py",
    )
    spec = importlib.util.spec_from_file_location("dpmr_reference_vectors", os.path.normpath(path))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def dpmr_symbol_stream(vectors):
    """FS2 plus body dibits, alternating the two reference superframe parts."""
    frames = [vectors.build_frame(spec) for spec in vectors.FRAME_SPECS]
    vectors.self_check(frames)
    fs2 = [int(char) for char in vectors.FS2_SYMBOLS]

    dibits = []
    for repeat in range(DPMR_SYNTH_FRAME_REPEATS):
        frame = frames[repeat % len(frames)]
        dibits += fs2
        dibits += frame["body"]
    return dibits


def modulate_4fsk(dibits, rng):
    """Continuous-phase 4FSK, one symbol at a time, with a noise lead-in.

    Rectangular symbols keep the eye fully open: the point of this fixture is a
    signal whose CCH decodes exactly, not a realistic channel. Impairment belongs
    in derived fixtures, the way p25p1_cqpsk_cc_simulcast adds it.
    """
    sps = SAMPLE_RATE_HZ // DPMR_SYNTH_SYMBOL_RATE
    if SAMPLE_RATE_HZ % DPMR_SYNTH_SYMBOL_RATE:
        raise ValueError("dPMR symbol rate must divide the fixture sample rate")

    # Outer symbols sit at +/-1050 Hz, so one level step is a third of that.
    step_rad = 2.0 * math.pi * (DPMR_SYNTH_OUTER_DEVIATION_HZ / 3.0) / SAMPLE_RATE_HZ

    lead_in = int(round(DPMR_SYNTH_LEAD_IN_S * SAMPLE_RATE_HZ))
    freq = np.zeros(lead_in + (len(dibits) * sps))
    for index, dibit in enumerate(dibits):
        start = lead_in + (index * sps)
        freq[start : start + sps] = DPMR_DIBIT_TO_LEVEL[dibit] * step_rad

    samples = np.exp(1j * np.cumsum(freq))
    samples[:lead_in] = 0.0
    noise = rng.normal(0.0, DPMR_SYNTH_NOISE_SIGMA, len(samples)) + 1j * rng.normal(
        0.0, DPMR_SYNTH_NOISE_SIGMA, len(samples)
    )
    return samples + noise


def build_dpmr_synth(out_dir):
    """Write the synthetic dPMR fixture built from the CCH reference vectors (#407)."""
    vectors = load_dpmr_reference_vectors()
    dibits = dpmr_symbol_stream(vectors)
    rng = np.random.default_rng(DPMR_SYNTH_SEED)
    samples = modulate_4fsk(dibits, rng)
    written = write_fixture(out_dir, DPMR_SYNTH_NAME, samples)
    print(f"{DPMR_SYNTH_NAME:28s} synth   {written // 1024:6d} KiB")
    return written


def build_derived(out_dir):
    total = 0
    for name, source, delay_samples, amp2, cfo_hz, phase2 in DERIVED_SIMULCAST:
        source_path = os.path.join(out_dir, source + ".iq")
        samples = load_cu8_fixture(source_path)
        impaired = simulcast_two_ray(samples, delay_samples, amp2, cfo_hz, phase2)
        written = write_fixture(out_dir, name, impaired)
        total += written
        print(f"{name:28s} derived {written // 1024:6d} KiB")
    return total


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", default=os.path.join("tests", "fixtures", "iq"))
    parser.add_argument("--cache", default=".iq-fixture-cache")
    parser.add_argument(
        "--derived-only",
        action="store_true",
        help="only regenerate fixtures derived from committed ones (no network/ffmpeg)",
    )
    parser.add_argument(
        "--only",
        action="append",
        help="regenerate just the named fixture(s); other fixtures and their downloads are skipped",
    )
    args = parser.parse_args()

    os.makedirs(args.out, exist_ok=True)

    total = 0
    if not args.derived_only:
        os.makedirs(args.cache, exist_ok=True)

        selected = [entry for entry in FIXTURES if not args.only or entry[0] in args.only]
        needed = {entry[1] for entry in selected}

        resolved = {}
        for key, url in SOURCES.items():
            members = ZIP_MEMBERS.get(key)
            wanted = key in needed if members is None else any(member in needed for member in members)
            if not wanted:
                continue
            path = fetch(args.cache, key, url)
            if members:
                resolved.update(extract_zip_members(args.cache, key, path))
            else:
                resolved[key] = path
        for key in LOCAL_SOURCES:
            if key not in needed:
                continue
            path = resolve_local(args.cache, key)
            if path is not None:
                resolved[key] = path
                continue
            message = (
                f"local source for {key} not found; place the contributed file at "
                f"{os.path.join(args.cache, LOCAL_SOURCES[key])} (see LOCAL_SOURCES for provenance)"
            )
            if args.only:
                raise FileNotFoundError(message)
            print(f"WARNING: {message}; skipping dependent fixtures", file=sys.stderr)

        for name, source_key, kind, start_s, duration_s, deviation in selected:
            if source_key not in resolved:
                print(f"{name:28s} skipped (source {source_key} unavailable)")
                continue
            path = resolved[source_key]
            if kind == "iq":
                samples = load_iq(path, start_s, duration_s)
            else:
                audio = ffmpeg_read(path, 1, start_s, duration_s)
                samples = remodulate(audio, deviation or DEFAULT_DEVIATION)
            written = write_fixture(args.out, name, samples)
            total += written
            print(f"{name:28s} {kind:5s}   {written // 1024:6d} KiB")

    if not args.only:
        total += build_derived(args.out)
        total += build_noise(args.out)
        total += build_dpmr_synth(args.out)
    else:
        for entry in DERIVED_SIMULCAST + [(n,) for n, _, _, _ in DERIVED_NOISE] + [(DPMR_SYNTH_NAME,)]:
            if entry[0] in args.only:
                raise SystemExit(f"{entry[0]} is a derived fixture; regenerate it with --derived-only")
    print(f"total {total // 1024} KiB in {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
